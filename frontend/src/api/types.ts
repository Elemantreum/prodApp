// Mirrors backend/internal/{training,booking}/model.go exactly — keep in
// sync by hand, there's no shared codegen between the two sides.

export interface Training {
  id: number;
  description: string;
  /** ISO 8601 timestamp */
  date: string;
  maxQuantity: number;
  /** Go time.Duration, marshalled as nanoseconds */
  duration: number;
  isActive: boolean;
  createdAt: string;
  /** How many active bookings this training currently has — joined in on
   *  the backend, no separate request needed to show it on the card. */
  bookedCount: number;
  /** Set if this training was generated by a recurring rule (see
   *  RecurringTraining) — purely informational, editable like any other. */
  recurringTrainingId?: number | null;
}

/** Правило "эта тренировка повторяется каждую неделю" — см.
 *  RecurringService.GenerateOccurrences на бэке. anchorDate — дата и время
 *  первого занятия, дальше каждые 7 дней от неё. */
export interface RecurringTraining {
  id: number;
  description: string;
  /** ISO 8601 timestamp — первое занятие */
  anchorDate: string;
  maxQuantity: number;
  /** nanoseconds */
  duration: number;
  /** nanoseconds — за сколько до даты занятия его нужно материализовать в
   *  общий список тренировок. */
  leadTime: number;
  isActive: boolean;
  createdAt: string;
}

export type BookingStatus = "active" | "cancelled" | "completed" | "not_completed";

export interface Booking {
  id: number;
  userId: number;
  trainingId: number;
  status: BookingStatus;
  bookingDate: string;
  unbookingDate: string | null;
}

export interface Participant {
  userId: number;
  firstName: string;
  lastName: string;
  username: string;
  bookingDate: string;
}

/** Админский взгляд на одну запись на тренировку — в отличие от Participant
 *  включает id брони (нужен для setAttendance) и статус, и не отфильтрован
 *  по статусу (сюда попадают и отменённые). См. TrainingAdminModal. */
export interface BookingDetail {
  bookingId: number;
  userId: number;
  firstName: string;
  lastName: string;
  username: string;
  status: BookingStatus;
  bookingDate: string;
}

export interface CreateTrainingInput {
  description: string;
  /** ISO 8601 timestamp */
  date: string;
  maxQuantity: number;
  /** nanoseconds */
  duration: number;
}

export interface AuthResponse {
  access_token: string;
}

export interface LinkCode {
  code: string;
  /** ISO 8601 timestamp */
  expiresAt: string;
}

export interface Identity {
  provider: string;
  externalId: string;
}

export interface User {
  id: number;
  username: string;
  firstName: string;
  lastName: string;
  isApproved: boolean;
  isAdmin: boolean;
  /** Прошёл ли обязательный шаг "как вас зовут" при первом входе — см.
   *  RegistrationGate. Пока false, приложение показывает только этот шаг. */
  isRegistered: boolean;
  createdAt: string;
  updatedAt: string;
  /** All platforms linked to this account — can be more than one after
   *  account linking (see AccountPage). */
  identities: Identity[];
}
